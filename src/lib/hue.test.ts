import { describe, it, expect } from "vitest";
import { rgbToHsl, pickHue } from "./hue";

describe("rgbToHsl", () => {
  it("переводит чистый красный", () => {
    const [h, s, l] = rgbToHsl(255, 0, 0);
    expect(h).toBe(0);
    expect(s).toBeCloseTo(1, 2);
    expect(l).toBeCloseTo(0.5, 2);
  });

  it("переводит чистый синий", () => {
    expect(rgbToHsl(0, 0, 255)[0]).toBe(240);
  });

  it("у серого насыщенность нулевая", () => {
    expect(rgbToHsl(128, 128, 128)[1]).toBeCloseTo(0, 3);
  });
});

describe("pickHue", () => {
  it("берёт самый частый оттенок", () => {
    // Три насыщенных синих пикселя (корзина 24) против одного красного
    // (корзина 0). Большинство нарочно лежит в СТАРШЕЙ корзине: если бы
    // перебор побеждал первую непустую корзину вместо самой полной, тест
    // остался бы зелёным просто потому, что победитель стоит в начале
    // массива — этот порядок уже подводил (см. соседние тесты ниже).
    const px = new Uint8ClampedArray([
      30, 30, 220, 255,
      30, 30, 220, 255,
      30, 30, 220, 255,
      220, 30, 30, 255,
    ]);
    const hue = pickHue(px);
    expect(hue).not.toBeNull();
    expect(hue!).toBeGreaterThan(220);
    expect(hue!).toBeLessThan(260);
  });

  it("отбрасывает блёклые пиксели", () => {
    // Три одинаковых почти-серых пикселя — намеренно один и тот же оттенок
    // (0°), а не три разных: если бы отбор по блёклости не работал, их
    // большинство (3 против 1) перевесило бы одиночный насыщенный синий, и
    // тест остался бы зелёным просто по случайности бинов. Так победить
    // может только синий, и только если серые действительно отброшены.
    const px = new Uint8ClampedArray([
      130, 128, 128, 255,
      130, 128, 128, 255,
      130, 128, 128, 255,
      30, 30, 220, 255,
    ]);
    const hue = pickHue(px);
    expect(hue).not.toBeNull();
    expect(hue!).toBeGreaterThan(200);
    expect(hue!).toBeLessThan(280);
  });

  it("отбрасывает слишком тёмное и слишком светлое", () => {
    // Оба края нарочно взяты полностью насыщенными (s = 1), чтобы их не
    // отсеяла проверка блёклости раньше проверки светлоты — иначе, как было
    // раньше с почти-белым (s ≈ 0.17), ветка верхней границы вообще не
    // выполнялась бы, а тест всё равно оставался зелёным.
    const px = new Uint8ClampedArray([
      8, 0, 0, 255,
      255, 200, 200, 255,
      30, 30, 220, 255,
    ]);
    const hue = pickHue(px);
    expect(hue).not.toBeNull();
    expect(hue!).toBeGreaterThan(200);
    expect(hue!).toBeLessThan(280);
  });

  it("на почти сером отказывается молча", () => {
    // Отказ обязан быть тихим: оттенок остаётся заданным в палитре, а не
    // становится случайным.
    const px = new Uint8ClampedArray([
      128, 128, 128, 255,
      130, 130, 130, 255,
    ]);
    expect(pickHue(px)).toBeNull();
  });

  it("на пустых данных отказывается молча", () => {
    expect(pickHue(new Uint8ClampedArray([]))).toBeNull();
  });
});
